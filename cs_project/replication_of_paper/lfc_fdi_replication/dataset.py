"""
dataset.py
==========
Builds the supervised datasets used to train:

  * the DL-LSTM detector  -> windows labelled Normal / Single / Multi (layer-1)
                             plus a 6-dim per-channel attack mask (layer-2), and
  * the BiGRU defender     -> clean windows with next-step targets (regression).

Data are generated by simulating the 3-area LFC plant (lfc_model) under random
RES/load disturbances and random FDI attack scenarios (attacks), then sampled at
DT_ML and sliced into overlapping windows of length WINDOW_LEN (Section IV-B).
"""

from __future__ import annotations
import numpy as np
from dataclasses import dataclass
from typing import Tuple
import config as C
from lfc_model import ThreeAreaLFC, make_disturbances
from attacks import apply_attacks, sample_random_attacks, Attack


# --------------------------------------------------------------------------- #
def simulate_episode(seed: int, t_end: float, attacks=None):
    """Run one plant episode; return (t, clean_meas, attacked_meas, ch_labels)."""
    g = np.random.default_rng(seed)
    plant = ThreeAreaLFC()
    Pd, Pres = make_disturbances(seed=seed, t_end=t_end)
    out = plant.simulate(t_end, C.DT_SIM, Pd, Pres)

    # downsample to ML rate
    stride = int(round(C.DT_ML / C.DT_SIM))
    t = out["t"][::stride]
    clean = np.hstack([out["df"][::stride], out["Ptie"][::stride]])   # (N,6)

    if attacks is None:
        attacks = sample_random_attacks(g, t_end)
    att, ch_lab = apply_attacks(clean, t, attacks)
    return t, clean, att, ch_lab, attacks


# --------------------------------------------------------------------------- #
def _windows(sig: np.ndarray, lab: np.ndarray, L: int, stride: int):
    """Slice (N,6) into windows; label taken at the window's last step."""
    Xs, Y1s, YCs = [], [], []
    N = sig.shape[0]
    for s in range(0, N - L, stride):
        w = sig[s:s + L]
        end_lab = lab[s + L - 1]                 # per-channel mask at window end
        n_att = int(end_lab.sum())
        y1 = 0 if n_att == 0 else (1 if n_att == 1 else 2)
        Xs.append(w); Y1s.append(y1); YCs.append(end_lab)
    return np.array(Xs), np.array(Y1s), np.array(YCs)


# --------------------------------------------------------------------------- #
@dataclass
class Scaler:
    """Per-channel standardiser fitted on clean training data."""
    mean: np.ndarray
    std: np.ndarray

    def transform(self, x):
        return (x - self.mean) / self.std

    def inverse(self, x):
        return x * self.std + self.mean


def build_datasets(n_episodes: int = C.N_TRAIN_EPISODES,
                   t_end: float = C.T_END,
                   window: int = C.WINDOW_LEN,
                   stride: int = 4):
    """
    Returns a dict with detector and defender tensors plus the fitted scaler.
    Split: 70% train/val, 30% test (Section IV-B).
    """
    g = np.random.default_rng(C.SEED)

    clean_all, att_all, lab_all = [], [], []
    for e in range(n_episodes):
        seed = int(g.integers(0, 2**31 - 1))
        _, clean, att, lab, _ = simulate_episode(seed, t_end)
        clean_all.append(clean); att_all.append(att); lab_all.append(lab)

    # fit scaler on clean data
    stacked = np.vstack(clean_all)
    scaler = Scaler(mean=stacked.mean(0), std=stacked.std(0) + 1e-8)

    # ---- detector windows (from attacked signals) --------------------------
    Xdet, Y1, YC = [], [], []
    for att, lab in zip(att_all, lab_all):
        x, y1, yc = _windows(scaler.transform(att), lab, window, stride)
        Xdet.append(x); Y1.append(y1); YC.append(yc)
    Xdet = np.concatenate(Xdet); Y1 = np.concatenate(Y1); YC = np.concatenate(YC)

    # ---- defender windows (from CLEAN signals: predict next-step) ----------
    Xdef, Ydef = [], []
    def_stride = 2
    for clean in clean_all:
        cs = scaler.transform(clean)
        for s in range(0, cs.shape[0] - window, def_stride):
            Xdef.append(cs[s:s + window])
            Ydef.append(cs[s + window])              # next-step target
    Xdef = np.array(Xdef); Ydef = np.array(Ydef)

    # ---- train / test split ------------------------------------------------
    def split(*arrs, frac=0.7):
        n = arrs[0].shape[0]
        idx = np.random.default_rng(C.SEED).permutation(n)
        cut = int(frac * n)
        tr = tuple(a[idx[:cut]] for a in arrs)
        te = tuple(a[idx[cut:]] for a in arrs)
        return tr, te

    (Xdet_tr, Y1_tr, YC_tr), (Xdet_te, Y1_te, YC_te) = split(Xdet, Y1, YC)
    (Xdef_tr, Ydef_tr), (Xdef_te, Ydef_te) = split(Xdef, Ydef)

    return {
        "scaler": scaler,
        "det": {
            "Xtr": Xdet_tr, "y1tr": Y1_tr, "yctr": YC_tr,
            "Xte": Xdet_te, "y1te": Y1_te, "ycte": YC_te,
        },
        "def": {
            "Xtr": Xdef_tr, "Ytr": Ydef_tr,
            "Xte": Xdef_te, "Yte": Ydef_te,
        },
    }


if __name__ == "__main__":
    d = build_datasets(n_episodes=20)
    print("detector train :", d["det"]["Xtr"].shape,
          "labels dist:", np.bincount(d["det"]["y1tr"], minlength=3))
    print("defender train :", d["def"]["Xtr"].shape, d["def"]["Ytr"].shape)
